// One-off generator: reads the legacy src/App.jsx and writes src/routes/cityRoutes.js
// (lazy-loaded page/detail components + data loaders). Re-run only after pointing it at a file that still has the static imports.
import fs from 'fs';
const src = fs.readFileSync(process.argv[2] || 'src/App.jsx', 'utf8');

const defaults = {}; // Component -> path
for (const m of src.matchAll(/^import (\w+) from '(\.\/pages\/[^']+)';/gm)) defaults[m[1]] = m[2];
const getters = {}; // getter -> path
for (const m of src.matchAll(/^import \{ (\w+) \} from '(\.\/pages\/[^']+)';/gm)) getters[m[1]] = m[2];

const cities = [];
for (const m of src.matchAll(/\{ key: '([^']+)', label: '([^']+)', getCard: (\w+), Detail: (\w+) \}/g)) {
  cities.push({ key: m[1], label: m[2], getter: m[3], detail: m[4] });
}

const routes = [];
for (const m of src.matchAll(/<Route path="(\/coworking\/[^"]+)" element=\{<(\w+) \/>\} \/>/g)) {
  if (m[2] === 'Navigate') continue;
  routes.push({ path: m[1], comp: m[2] });
}
const redirects = [];
for (const m of src.matchAll(/<Route path="(\/coworking\/[^"]+)" element=\{<Navigate to="([^"]+)" replace \/>\} \/>/g)) redirects.push([m[1], m[2]]);

const used = new Set([...routes.map((r) => r.comp), ...cities.map((c) => c.detail)]);
const lazyLines = [...used].map((c) => {
  if (!defaults[c]) throw new Error('No import for ' + c);
  return `const ${c} = lazy(() => import('.${defaults[c]}'));`;
});

const out = `// GENERATED by scripts/gen-routes.mjs from the old App.jsx. Edit freely: add a city by adding a lazy import,
// a line in coworkingRoutes and a line in officeCities.
import { lazy } from 'react';

${lazyLines.join('\n')}

// Every /coworking/... page and office-detail route.
export const coworkingRoutes = [
${routes.map((r) => `  { path: '${r.path}', Component: ${r.comp} },`).join('\n')}
];

// Old / alternate spellings that redirect to the real page.
export const coworkingRedirects = [
${redirects.map(([a, b]) => `  ['${a}', '${b}'],`).join('\n')}
];

// Cities with office detail pages. The data chunk is only downloaded when a page needs it.
export const officeCities = [
${cities.map((c) => {
  const dataPath = getters[c.getter];
  if (!dataPath) throw new Error('No data import for ' + c.getter);
  return `  { key: '${c.key}', label: '${c.label.replace(/'/g, "\'")}', loadData: () => import('.${dataPath}'), getter: '${c.getter}', Detail: ${c.detail} },`;
}).join('\n')}
];
`;
fs.writeFileSync('src/routes/cityRoutes.js', out);
console.log({ lazy: used.size, routes: routes.length, cities: cities.length, redirects: redirects.length });
